#!/usr/bin/env python3
import shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DESTINATION = ROOT / "licenses"
NAMES = {"LICENSE", "LICENSE.txt", "LICENSE.md", "COPYING", "COPYING.txt", "COPYING.md"}


def collect(source_root, destination_root):
    collected = []
    if not source_root.exists():
        return collected
    for source in sorted(source_root.rglob("*")):
        if not source.is_file() or source.name not in NAMES:
            continue
        relative = source.relative_to(source_root)
        target = destination_root / relative
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(source, target)
        collected.append(relative)
    return collected


def main():
    if DESTINATION.exists():
        shutil.rmtree(DESTINATION)
    vendor = collect(ROOT / "vendor", DESTINATION / "vendor")
    reference = collect(ROOT / "reference", DESTINATION / "reference")
    lines = [
        "# Third-party license texts",
        "",
        "This directory is generated by `scripts/collect-licenses.py` from the vendored",
        "and locally referenced source trees. Paths mirror those source trees.",
        "",
        f"- Vendored license files: {len(vendor)}",
        f"- Reference license files: {len(reference)}",
        "",
        "Project-specific licensing is documented in `LICENSE`, `NOTICE`, and",
        "`THIRD_PARTY.md` in the repository root.",
        "",
    ]
    (DESTINATION / "README.md").write_text("\n".join(lines))
    print(f"Collected {len(vendor) + len(reference)} license files")


if __name__ == "__main__":
    main()
